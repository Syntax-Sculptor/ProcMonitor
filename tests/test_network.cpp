#include "CppUTest/TestHarness.h"

TEST_GROUP(Network) {
    int sock_pair[2];
    bool created_sockets = false;

    TEST_SETUP() {
        if (socketpair(AF_UNIX, SOCK_STREAM, 0, sock_pair) == -1) {
            FAIL("Failed to create socketpair");
        }

        created_sockets = true;
    }
    
    TEST_TEARDOWN() {
        if (created_sockets) {
            close(sock_pair[0]);
            close(sock_pair[1]);
        }
    }
};

TEST(Network, recv_safe_reads_exact) {
    const uint8_t data[] = {
        // length prefix: 88 = 0x00000058
        0x00, 0x00, 0x00, 0x58,
        // timestamp = 258 (0x0102)
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x02,
        // user_time = 1
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01,
        // nice_time = 2
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x02,
        // system_time = 3
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x03,
        // idle_time = 4
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x04,
        // io_wait = 5
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x05,
        // irq = 6
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x06,
        // soft_irq = 7
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x07,
        // steal_time = 8
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x08,
        // guest_time = 9
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x09,
        // guest_nice_time = 10 (0x0A)
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x0A,
    };

    size_t length = Serialization::HEADER_SIZE + Serialization::PAYLOAD_SIZE;
    std::vector<uint8_t> frame(length);

    write(sock_pair[0], data, length);

    Network::TransmitState res = Network::recv_safe(
        sock_pair[1], 
        frame.data(), 
        length
    );
    CHECK_TRUE(res == Network::TransmitState::OK);
    MEMCMP_EQUAL(data, frame.data(), length);
}

